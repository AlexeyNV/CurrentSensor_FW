void DMA2_Stream3_IRQHandler(void) { AcqDma_TxIRQ(); }
void TIM2_IRQHandler(void)
{
  Timebase_UpdateIRQ();
  PairDiag_MarkerIRQ();
  if ((TIM2->SR & TIM_SR_CC1IF) != 0U &&
      (TIM2->DIER & TIM_DIER_CC1IE) != 0U)
    AcqDma_SettleIRQ();
}

